#!/usr/bin/env node
/**
 * Writes packages/shared/src/abis.ts from the Foundry build output, so the web
 * app and the keeper call the contracts with the exact ABI that was compiled.
 *
 *   npm run abi:export          # forge build, then regenerate
 *   npm run abi:check           # regenerate and fail if the file changed (CI)
 *
 * Enum members are read from the Solidity source, so an enum that gains or
 * reorders a member changes the generated constants instead of drifting.
 */

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contracts = path.join(root, "contracts");
const target = path.join(root, "packages", "shared", "src", "abis.ts");

const ABIS = [
  ["marketEscrowAbi", "MarketEscrow"],
  ["marketFactoryAbi", "MarketFactory"],
  ["templateRegistryAbi", "TemplateRegistry"],
  ["epochVaultAbi", "EpochVault"],
  ["erc20Abi", "MockERC20"],
  ["oracleAbi", "MockOracle"],
];

const ENUMS = [
  { name: "Phase", file: "src/Types.sol" },
  { name: "Closure", file: "src/Types.sol" },
  { name: "Side", file: "src/Types.sol" },
  { name: "EpochState", file: "src/EpochVault.sol" },
];

const check = process.argv.includes("--check");

function forgeBinary() {
  const home = process.env.USERPROFILE || process.env.HOME || "";
  const candidates = [
    "forge",
    path.join(home, ".foundry", "bin", process.platform === "win32" ? "forge.exe" : "forge"),
  ];
  for (const bin of candidates) {
    try {
      execFileSync(bin, ["--version"], { stdio: "ignore" });
      return bin;
    } catch {
      // try the next candidate
    }
  }
  throw new Error("forge was not found. Install Foundry (https://getfoundry.sh).");
}

function readAbi(contract) {
  const file = path.join(contracts, "out", `${contract}.sol`, `${contract}.json`);
  if (!fs.existsSync(file)) throw new Error(`Missing artifact ${file}. Run forge build.`);
  return JSON.parse(fs.readFileSync(file, "utf8")).abi;
}

function readEnum({ name, file }) {
  const source = fs.readFileSync(path.join(contracts, file), "utf8");
  const match = source.match(new RegExp(`enum\\s+${name}\\s*\\{([^}]*)\\}`));
  if (!match) throw new Error(`enum ${name} not found in ${file}`);
  const members = match[1]
    .split("\n")
    .map((line) => line.replace(/\/\/.*$/, "").replace(/,/g, "").trim())
    .filter(Boolean);
  if (members.length === 0) throw new Error(`enum ${name} has no members`);
  return members;
}

execFileSync(forgeBinary(), ["build", "--root", contracts], { stdio: "inherit" });

let out = `// Generated by scripts/export-abis.mjs from the Foundry build. Do not edit.
// Regenerate with \`npm run abi:export\`; CI runs \`npm run abi:check\`.

`;

for (const [constName, contract] of ABIS) {
  out += `export const ${constName} = ${JSON.stringify(readAbi(contract), null, 2)} as const;\n\n`;
}

for (const e of ENUMS) {
  const members = readEnum(e);
  out += `export const ${e.name} = {\n`;
  members.forEach((m, i) => {
    out += `  ${m}: ${i},\n`;
  });
  out += `} as const;\n\n`;
}

out = out.trimEnd() + "\n";

if (check) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current.replace(/\r\n/g, "\n") !== out) {
    console.error("packages/shared/src/abis.ts is out of date. Run `npm run abi:export`.");
    process.exit(1);
  }
  console.log("abis.ts is up to date.");
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, out);
  console.log(`Wrote ${path.relative(root, target)} (${ABIS.length} ABIs, ${ENUMS.length} enums).`);
}
