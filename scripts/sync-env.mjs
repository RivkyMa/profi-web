#!/usr/bin/env node
/**
 * Turns deployments/<chainId>.json (written by the deploy script) into the env
 * the web app and the keeper read.
 *
 *   npm run env:sync -- 31337
 *   RPC_URL=https://... npm run env:sync -- <chainId>
 *
 * Only the region between the markers is touched; anything else in the env
 * files (your own keys, overrides) is left alone. Nothing secret is written:
 * the keeper key is never put in a file by this script.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const START = "# >>> profi:deploy (generated by scripts/sync-env.mjs; edit outside these markers)";
const END = "# <<< profi:deploy";
const LOCAL_CHAIN_ID = 31337;

const chainId = Number(process.argv[2]);
if (!Number.isInteger(chainId) || chainId <= 0) {
  console.error("Usage: node scripts/sync-env.mjs <chainId>");
  process.exit(1);
}

const manifestPath = path.join(root, "deployments", `${chainId}.json`);
if (!fs.existsSync(manifestPath)) {
  console.error(`No manifest at ${path.relative(root, manifestPath)}. Run the deploy script first.`);
  process.exit(1);
}
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));

const rpcUrl = process.env.RPC_URL || (chainId === LOCAL_CHAIN_ID ? "http://127.0.0.1:8545" : "");
if (!rpcUrl) {
  console.error(`Set RPC_URL for chain ${chainId}; it is never guessed.`);
  process.exit(1);
}

const underlyings = manifest.underlyings
  .map((u) => `${u.symbol}:${u.token}:${u.oracle}`)
  .join(",");

const optional = (name) => (process.env[name] ? [`${name}=${process.env[name]}`] : []);

const web = [
  "NEXT_PUBLIC_DATA_MODE=chain",
  `NEXT_PUBLIC_CHAIN_ID=${chainId}`,
  `NEXT_PUBLIC_RPC_URL=${rpcUrl}`,
  `NEXT_PUBLIC_FACTORY_ADDRESS=${manifest.factory}`,
  `NEXT_PUBLIC_REGISTRY_ADDRESS=${manifest.registry}`,
  `NEXT_PUBLIC_VAULT_ADDRESS=${manifest.vault}`,
  `NEXT_PUBLIC_STABLE_ADDRESS=${manifest.stable}`,
  `NEXT_PUBLIC_UNDERLYINGS=${underlyings}`,
  `NEXT_PUBLIC_TEMPLATE_ID=${manifest.templateId}`,
  `NEXT_PUBLIC_START_BLOCK=${manifest.startBlock}`,
  ...(chainId === LOCAL_CHAIN_ID ? ["NEXT_PUBLIC_CHAIN_NAME=Anvil (local)"] : []),
  ...optional("NEXT_PUBLIC_CHAIN_NAME"),
  ...optional("NEXT_PUBLIC_NATIVE_SYMBOL"),
  ...optional("NEXT_PUBLIC_EXPLORER_URL"),
];

const keeper = [
  `RPC_URL=${rpcUrl}`,
  `CHAIN_ID=${chainId}`,
  `FACTORY_ADDRESS=${manifest.factory}`,
  `VAULT_ADDRESS=${manifest.vault}`,
];

function writeBlock(file, lines) {
  const block = [START, ...lines, END].join("\n");
  let content = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  const from = content.indexOf(START);
  const to = content.indexOf(END);
  if (from !== -1 && to > from) {
    content = content.slice(0, from) + block + content.slice(to + END.length);
  } else {
    content = content.trimEnd() + (content.trim() === "" ? "" : "\n\n") + block + "\n";
  }
  if (!content.endsWith("\n")) content += "\n";
  fs.writeFileSync(file, content);
  console.log(`Updated ${path.relative(root, file)} (${lines.length} variables)`);
}

writeBlock(path.join(root, "web", ".env.local"), web);
writeBlock(path.join(root, "keeper", ".env"), keeper);
console.log(
  chainId === LOCAL_CHAIN_ID
    ? "Local chain: the keeper uses the node's first unlocked account unless you set KEEPER_PRIVATE_KEY or KEEPER_ADDRESS."
    : "Set KEEPER_PRIVATE_KEY in keeper/.env (never commit it).",
);
